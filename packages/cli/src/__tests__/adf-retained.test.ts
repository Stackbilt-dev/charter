interface RestoreJson { status: string; refusal: string | null; keptSections: string[] }

describe('adf vendor restore of a compiled file with a retained block', () => {
  it('restores the pointer and carries the block sections into it', async () => {
    scaffold(vendors('CLAUDE.md: pointer'));
    const withBlock = `${(await fresh('claude')).trimEnd()}\n\n${block(`${ENV}\n\n## Deploy Protocol\n- staging first`)}`;
    fs.writeFileSync('CLAUDE.md', withBlock);
    const r = await run(['vendor', 'restore', 'CLAUDE.md', '--format', 'json'], JSON_OPTS);
    const json = JSON.parse(r.out) as RestoreJson;
    expect(json).toMatchObject({ status: 'restored', refusal: null, keptSections: ['## Environment', '## Deploy Protocol'] });
    const pointer = read('CLAUDE.md');
    expect(pointer).not.toContain(COMPILE_BANNER_MARKER);
    expect(pointer).not.toContain(RETAINED_START);
    expect(pointer.endsWith(`${ENV}\n\n## Deploy Protocol\n- staging first\n`)).toBe(true);
  });

  it('is compiled-differs only when something besides the block differs', async () => {
    scaffold(vendors('CLAUDE.md: pointer'));
    const withBlock = `${(await fresh('claude')).trimEnd()}\n\n${block(ENV)}`;
    fs.writeFileSync('CLAUDE.md', withBlock.replace('TypeScript', 'JavaScript'));
    const r = await run(['vendor', 'restore', 'CLAUDE.md', '--format', 'json'], JSON_OPTS);
    expect(JSON.parse(r.out)).toMatchObject({ status: 'refused', refusal: 'compiled-differs' });
  });
});

