function scaffold(manifest = BASE_MANIFEST): void {
  for (const [file, content] of Object.entries(MAIN_FIXTURE.inputs)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, file === '.ai/manifest.adf' ? manifest : content);
  }
}

function vendors(...entries: string[]): string {
  return `${BASE_MANIFEST}\n\u{1F3F7} VENDORS:\n${entries.map(e => `  - ${e}\n`).join('')}`;
}

const read = (file: string): string => fs.readFileSync(file, 'utf-8');

async function run(args: string[], options: CLIOptions = TEXT): Promise<{ code: number; out: string; err: string }> {
  out = [];
  err = [];
  const code = await adfCommand(options, args);
  return { code, out: out.join('\n'), err: err.join('\n') };
}

async function runJson<T = Record<string, unknown>>(args: string[]): Promise<{ code: number; json: T; err: string }> {
  const r = await run([...args, '--format', 'json'], JSON_OPTS);
  return { code: r.code, json: JSON.parse(r.out) as T, err: r.err };
}

async function fresh(target: string): Promise<string> {
  return (await run(['compile', '--target', target])).out;
}

interface WriteRow { file: string; status: string; previousMode: string | null; recordedMode: string | null; remedy: string | null; retainedSections: string[]; retainedSource: string }
interface WriteJson { written: string[]; refused: string[]; targets: WriteRow[]; nextActions: string[] }
interface CheckRow { file: string; status: string; staleReason: string | null; remedy: string | null }
interface CheckJson { upToDate: boolean; targets: CheckRow[]; nextActions: string[] }

