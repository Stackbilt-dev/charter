describe('compile keeps a compiled file\'s user sections (#303)', () => {
  it('--check reads stale (retained-unfenced) until one --write, which keeps them; then fresh and idempotent', async () => {
    scaffold();
    expect((await run(['compile', '--target', 'claude', '--write'])).code).toBe(0);
    const render = read('CLAUDE.md');
    fs.writeFileSync('CLAUDE.md', `${render}\n${ENV}\n`);

    const textCheck = await run(['compile', '--target', 'claude', '--check']);
    expect(textCheck.code).toBe(1);
    expect(textCheck.out).toContain('  [stale] CLAUDE.md — your ## Environment section(s) sit outside the retained block.\n          Run: charter adf compile --target claude --write  (keeps them)');
    const check = await runJson<CheckJson>(['compile', '--target', 'claude', '--check']);
    expect(check.json.targets[0]).toMatchObject({ status: 'stale', staleReason: 'retained-unfenced', remedy: 'charter adf compile --target claude --write' });

    const write = await runJson<WriteJson>(['compile', '--target', 'claude', '--write']);
    expect(write.code).toBe(0);
    expect(write.json.targets[0]).toMatchObject({ status: 'written', retainedSections: ['## Environment'], retainedSource: 'legacy' });
    const kept = read('CLAUDE.md');
    expect(kept).toBe(`${render.trimEnd()}\n\n${block(ENV)}`);

    const text = await run(['compile', '--target', 'claude', '--write']);
    expect(text.out).toContain('  [ok] Written CLAUDE.md (kept ## Environment)');
    expect(read('CLAUDE.md')).toBe(kept);
    const again = await runJson<CheckJson>(['compile', '--target', 'claude', '--check']);
    expect(again.json.targets[0]).toMatchObject({ status: 'fresh', staleReason: null });

    // Edit inside the block: still fresh, and kept by the next write.
    const edited = kept.replace('- Use WSL for builds', '- Use WSL for builds\n- And pnpm 9');
    fs.writeFileSync('CLAUDE.md', edited);
    expect((await run(['compile', '--target', 'claude', '--check'])).code).toBe(0);
    await run(['compile', '--target', 'claude', '--write']);
    expect(read('CLAUDE.md')).toBe(edited);

    // Delete the whole block: it stays deleted.
    fs.writeFileSync('CLAUDE.md', edited.slice(0, edited.indexOf(RETAINED_START)));
    await run(['compile', '--target', 'claude', '--write']);
    expect(read('CLAUDE.md')).toBe(render);
  });

  it('a content change still reads stale with staleReason content', async () => {
    scaffold();
    await run(['compile', '--target', 'claude', '--write']);
    fs.writeFileSync('CLAUDE.md', `${read('CLAUDE.md').replace('TypeScript', 'JavaScript')}\n${block(ENV)}`);
    const check = await runJson<CheckJson>(['compile', '--target', 'claude', '--check']);
    expect(check.json.targets[0]).toMatchObject({ status: 'stale', staleReason: 'content' });
  });

  it('two --write runs are byte-identical for every target, with and without a block, LF and CRLF (INV-P5-3)', async () => {
    scaffold();
    await run(['compile', '--target', 'all', '--write']);
    const plain = Object.fromEntries(TARGET_FILES.map(f => [f, read(f)]));
    await run(['compile', '--target', 'all', '--write']);
    for (const f of TARGET_FILES) expect(read(f), f).toBe(plain[f]);

    for (const f of TARGET_FILES) fs.writeFileSync(f, `${plain[f]}\n${ENV}\n`.replace(/\n/g, '\r\n'));
    await run(['compile', '--target', 'all', '--write']);
    const kept = Object.fromEntries(TARGET_FILES.map(f => [f, read(f)]));
    await run(['compile', '--target', 'all', '--write']);
    for (const f of TARGET_FILES) {
      expect(read(f), f).toBe(kept[f]);
      expect(kept[f], f).toBe(`${plain[f].trimEnd()}\n\n${block(ENV)}`);
    }
    // .cursorrules uses the HTML markers too (CP-3).
    expect(kept['.cursorrules'].startsWith('# GENERATED')).toBe(true);
    expect(kept['.cursorrules']).toContain(RETAINED_START);
    expect((await run(['compile', '--target', 'all', '--check'])).code).toBe(0);
  });

  it('warns on a heading collision and keeps both (R4)', async () => {
    scaffold();
    await run(['compile', '--target', 'claude', '--write']);
    const withCollision = `${read('CLAUDE.md')}\n${block('## CONTEXT\n- my context')}`;
    fs.writeFileSync('CLAUDE.md', withCollision);
    const r = await run(['compile', '--target', 'claude', '--write']);
    expect(r.code).toBe(0);
    expect(r.err).toContain('CLAUDE.md: your retained section ## CONTEXT has the same heading as a compiled section; both are kept.');
    expect(read('CLAUDE.md')).toBe(withCollision);
    const json = await run(['compile', '--target', 'claude', '--write', '--format', 'json'], JSON_OPTS);
    expect(() => JSON.parse(json.out)).not.toThrow();
  });

  it('stdout mode prints the pure render even when the file has a block (INV-P5-7)', async () => {
    scaffold();
    await run(['compile', '--target', 'claude', '--write']);
    const render = read('CLAUDE.md');
    fs.writeFileSync('CLAUDE.md', `${render}\n${ENV}\n`);
    await run(['compile', '--target', 'claude', '--write']);
    expect(await fresh('claude')).toBe(render);
  });
});

