describe('composeCompiled', () => {
  it('returns the fresh render byte for byte when there is nothing to carry (P3)', () => {
    expect(composeCompiled(FRESH, null, 'CLAUDE.md')).toMatchObject({ output: FRESH, retainedSource: 'none', retainedSections: [] });
    const edited = FRESH.replace('- a', '- a hand edit');
    expect(composeCompiled(FRESH, edited, 'CLAUDE.md')).toMatchObject({ output: FRESH, retainedSource: 'none' });
  });

  it('moves a legacy user section into a block at the very end; the banner stays line 1 (P1, W1)', () => {
    const legacy = `${FRESH}\n${ENV}\n`;
    const c = composeCompiled(FRESH, legacy, 'CLAUDE.md');
    expect(c).toMatchObject({ retainedSource: 'legacy', retainedSections: ['## Environment'], unfenced: ['## Environment'] });
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${block(ENV)}`);
    expect(c.output.split('\n')[0]).toBe(`<!-- ${COMPILE_BANNER_MARKER} -->`);
  });

  it('is idempotent for every source (R1, INV-P5-3)', () => {
    const inputs: Record<string, string> = {
      legacy: `${FRESH}\n${ENV}\n`,
      block: `${FRESH}\n${block(ENV)}`,
      pointer: `${POINTER_AGENTS_MD}\n## Release Protocol\n\n- Tag first.\n`,
      unmanaged: '# Mine\n\nHouse rules.\n\n## Environment\n- WSL\n',
    };
    for (const [name, input] of Object.entries(inputs)) {
      const file = name === 'pointer' ? 'AGENTS.md' : 'CLAUDE.md';
      const once = composeCompiled(FRESH, input, file);
      expect(once.retainedSource, name).toBe(name);
      expect(composeCompiled(FRESH, once.output, file).output, name).toBe(once.output);
    }
  });

  it('copies an existing block verbatim, so an edit inside it changes nothing (C1, INV-P5-5)', () => {
    const edited = `${FRESH}\n${RETAINED_START}\n\nmy own preface line\n${ENV}\n- second note\n\n\n${RETAINED_END}\n`;
    const c = composeCompiled(FRESH, edited, 'CLAUDE.md');
    expect(c.output).toBe(edited);
    expect(c.retainedSections).toEqual(['## Environment']);
  });

  it('keeps a section deleted inside the block deleted; deleting the whole block means nothing is carried (R2)', () => {
    const two = composeCompiled(FRESH, `${FRESH}\n${ENV}\n\n## Release Protocol\n- tag\n`, 'CLAUDE.md').output;
    const oneLeft = two.replace('## Release Protocol\n- tag\n', '');
    expect(composeCompiled(FRESH, oneLeft, 'CLAUDE.md').output).toBe(oneLeft);
    expect(composeCompiled(FRESH, oneLeft, 'CLAUDE.md').output).not.toContain('Release Protocol');
    const noBlock = oneLeft.slice(0, oneLeft.indexOf(RETAINED_START));
    expect(composeCompiled(FRESH, noBlock, 'CLAUDE.md').output).toBe(FRESH);
  });

  it('keeps several sections in source order, and turns CRLF input into stable LF output (P2)', () => {
    const legacy = `${FRESH}\n## Session Protocol\n- one\n\n${ENV}\n`.replace(/\n/g, '\r\n');
    const c = composeCompiled(FRESH, legacy, 'CLAUDE.md');
    expect(c.retainedSections).toEqual(['## Session Protocol', '## Environment']);
    expect(c.output).not.toContain('\r');
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${block(`## Session Protocol\n- one\n\n${ENV}`)}`);
    expect(composeCompiled(FRESH, c.output, 'CLAUDE.md').output).toBe(c.output);
  });

  it('keeps a block section whose heading matches a compiled one, and reports the collision (R4)', () => {
    const withRules = `${FRESH}\n${block('## RULES\n- my rule')}`;
    const c = composeCompiled(FRESH, withRules, 'CLAUDE.md');
    expect(c.output).toBe(withRules);
    expect(c.collisions).toEqual(['## RULES']);
  });

  it('never resurrects a generated heading from a legacy file (INV-P5-4, #296 class)', () => {
    expect(GENERATED_HEADING_RE.test('## PROTOCOL')).toBe(true);
    expect(GENERATED_HEADING_RE.test('## RELEASE_PROTOCOL _(advisory)_')).toBe(true);
    // A module since removed from .ai/ left these behind in the compiled file.
    const stale = `${FRESH}\n## PROTOCOL\n\n- old rule\n\n## RELEASE_PROTOCOL _(advisory)_\n\n- old\n\n## SESSION\n\n- old\n`;
    const c = composeCompiled(FRESH, stale, 'CLAUDE.md');
    expect(c.output).toBe(FRESH);
    expect(c.retainedSource).toBe('none');
  });

  it('never carries ## Module Index or ## Session Start', () => {
    const legacy = `${FRESH}\n## Module Index\n| x |\n\n## Session Start\nCall it.\n`;
    expect(composeCompiled(FRESH, legacy, 'CLAUDE.md').output).toBe(FRESH);
  });

  it('falls back to legacy when an end marker has no start, dropping the stray marker (R3)', () => {
    const stray = `${FRESH}\n${ENV}\n${RETAINED_END}\n`;
    const c = composeCompiled(FRESH, stray, 'CLAUDE.md');
    expect(c.retainedSource).toBe('legacy');
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${block(ENV)}`);
  });

  it('runs a start marker with no end to EOF, then closes it, stably (R3)', () => {
    const open = `${FRESH}\n${RETAINED_START}\n${ENV}\n`;
    const c = composeCompiled(FRESH, open, 'CLAUDE.md');
    expect(c).toMatchObject({ retainedSource: 'block', retainedSections: ['## Environment'] });
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${RETAINED_START}\n${ENV}\n${RETAINED_END}\n`);
    expect(composeCompiled(FRESH, c.output, 'CLAUDE.md').output).toBe(c.output);
    // The stripper agrees: an unmatched start strips to EOF.
    expect(stripCharterSentinels(open)).not.toContain('Use WSL');
  });

  it('takes retained sections that sit outside an existing block into it', () => {
    const both = `${FRESH}\n## Session Protocol\n- new\n\n${block(ENV)}`;
    const c = composeCompiled(FRESH, both, 'CLAUDE.md');
    expect(c).toMatchObject({ retainedSource: 'block', unfenced: ['## Session Protocol'], retainedSections: ['## Session Protocol', '## Environment'] });
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${block(`## Session Protocol\n- new\n\n${ENV}`)}`);
  });

  it('does not carry a retained-looking line the render itself emits (a .ai/ text value)', () => {
    const withEmbedded = FRESH.replace('- a', '- a\n## Environment\n- from .ai/');
    expect(composeCompiled(withEmbedded, withEmbedded, 'CLAUDE.md').output).toBe(withEmbedded);
  });

  it('ends a legacy section at the module index fence instead of swallowing it', () => {
    const inserted = FRESH.replace('<!-- agents-modules -->', `${ENV}\n\n<!-- agents-modules -->`);
    const c = composeCompiled(FRESH, inserted, 'CLAUDE.md');
    expect(c.output).toBe(`${FRESH.trimEnd()}\n\n${block(ENV)}`);
  });

  it('carries only the divergent retained sections of a pointer (source pointer)', () => {
    const pristine = composeCompiled(FRESH, POINTER_CLAUDE_MD_HYBRID, 'CLAUDE.md');
    expect(pristine.output).toBe(FRESH);
    const notes = POINTER_CLAUDE_MD_HYBRID.replace('<!-- Add runtime/OS/shell-specific notes here (not stack rules) -->', '- WSL');
    expect(composeCompiled(FRESH, notes, 'CLAUDE.md')).toMatchObject({ retainedSource: 'pointer', retainedSections: ['## Environment'], body: '## Environment\n- WSL' });
  });

  it('linesConvertWouldDrop ignores template lines and the module index, and names the rest', () => {
    const notes = POINTER_CLAUDE_MD.replace('<!-- Add runtime/OS/shell-specific notes here (not stack rules) -->', '- WSL');
    expect(linesConvertWouldDrop(notes, composeCompiled(FRESH, notes, 'CLAUDE.md').output)).toEqual([]);
    const stray = POINTER_CLAUDE_MD.replace('# CLAUDE.md', '# CLAUDE.md\n\n> my own note');
    expect(linesConvertWouldDrop(stray, composeCompiled(FRESH, stray, 'CLAUDE.md').output)).toEqual(['> my own note']);
  });

  it('compiledMatchesFresh ignores the block and legacy sections, but not other edits (K2)', () => {
    expect(compiledMatchesFresh(FRESH, `${FRESH}\n${block(ENV)}`, 'CLAUDE.md')).toBe(true);
    expect(compiledMatchesFresh(FRESH, `${FRESH}\n${ENV}\n`, 'CLAUDE.md')).toBe(true);
    expect(compiledMatchesFresh(FRESH, FRESH.replace('- b', '- edited'), 'CLAUDE.md')).toBe(false);
  });

  it('the block is a charter sentinel: tidy, doctor and migrate strip it (K5)', () => {
    expect(stripCharterSentinels(`${FRESH}\n${block(ENV)}`)).not.toContain('Use WSL');
  });
});

